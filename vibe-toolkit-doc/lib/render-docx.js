/**
 * render-docx.js — render the system model to docs/SYSTEM.docx
 *
 * Mirrors render-md.js structure so the two outputs stay aligned. The
 * Solution Graph section embeds the same three views (ASCII as a code
 * paragraph, Mermaid source as a code paragraph, JSON spec as a code
 * paragraph). No rasterised PNG — keeps the doc machine-parseable and
 * avoids a Chromium dep just to render diagrams.
 */

import {
  Document, Packer, Paragraph, TextRun, HeadingLevel, AlignmentType,
  Table, TableRow, TableCell, WidthType, BorderStyle, ShadingType, PageBreak,
} from 'docx';

function fmtDate(iso) {
  if (!iso) return '—';
  return new Date(iso).toISOString().replace('T', ' ').slice(0, 19) + ' UTC';
}

// ── Block helpers ───────────────────────────────────────────────────────────

function p(text, opts = {}) {
  return new Paragraph({
    spacing: { after: 120 },
    ...opts,
    children: [new TextRun({ text: text ?? '', ...opts.run })],
  });
}

function h(text, level) {
  return new Paragraph({
    heading: level,
    spacing: { before: 240, after: 120 },
    children: [new TextRun({ text })],
  });
}

function bold(text) { return new TextRun({ text, bold: true }); }
function mono(text) { return new TextRun({ text, font: 'Consolas', size: 18 }); }
function italic(text) { return new TextRun({ text, italics: true }); }

function bulletList(items) {
  return items.map(text =>
    new Paragraph({
      bullet: { level: 0 },
      spacing: { after: 60 },
      children: [new TextRun({ text })],
    })
  );
}

function codeBlock(text) {
  // Render multi-line code as a single paragraph per line with monospaced font.
  const lines = text.split('\n');
  return lines.map(line =>
    new Paragraph({
      spacing: { after: 0 },
      shading: { type: ShadingType.SOLID, color: 'F5F5F5', fill: 'F5F5F5' },
      children: [mono(line || ' ')],
    })
  );
}

function quote(text) {
  return new Paragraph({
    indent: { left: 720 },
    spacing: { after: 120 },
    border: { left: { color: '888888', style: BorderStyle.SINGLE, size: 6, space: 12 } },
    children: [italic(text)],
  });
}

// ── Table helpers ───────────────────────────────────────────────────────────

const HEADER_SHADING = { type: ShadingType.SOLID, color: 'EEEEEE', fill: 'EEEEEE' };

function cell(content, opts = {}) {
  const children = typeof content === 'string'
    ? [new Paragraph({ spacing: { after: 40 }, children: [new TextRun({ text: content, bold: opts.header })] })]
    : Array.isArray(content) ? content : [content];
  return new TableCell({
    children,
    shading: opts.header ? HEADER_SHADING : undefined,
    width: opts.width ? { size: opts.width, type: WidthType.PERCENTAGE } : undefined,
  });
}

function table(headers, rows) {
  return new Table({
    width: { size: 100, type: WidthType.PERCENTAGE },
    rows: [
      new TableRow({ children: headers.map(h => cell(h, { header: true })) }),
      ...rows.map(r => new TableRow({ children: r.map(c => cell(c)) })),
    ],
  });
}

// ── Section renderers ───────────────────────────────────────────────────────

function renderCover(model) {
  return [
    new Paragraph({
      heading: HeadingLevel.TITLE,
      alignment: AlignmentType.CENTER,
      spacing: { before: 1440, after: 240 },
      children: [new TextRun({ text: model.name, bold: true, size: 56 })],
    }),
    new Paragraph({
      alignment: AlignmentType.CENTER,
      spacing: { after: 480 },
      children: [new TextRun({ text: 'System Documentation', size: 32 })],
    }),
    new Paragraph({
      alignment: AlignmentType.CENTER,
      spacing: { after: 240 },
      children: [new TextRun({ text: `Version ${model.version}`, size: 24 })],
    }),
    new Paragraph({
      alignment: AlignmentType.CENTER,
      spacing: { after: 240 },
      children: [new TextRun({ text: `Generated ${fmtDate(new Date().toISOString())}`, size: 20 })],
    }),
    new Paragraph({
      alignment: AlignmentType.CENTER,
      spacing: { after: 720 },
      children: [new TextRun({ text: `Repository: ${model.repo}`, size: 18 })],
    }),
    quote(`Auto-generated by vibe-toolkit-doc. Do not edit by hand — edit vibe-toolkit-doc/lib/system-model.js and re-run node vibe-toolkit-doc/index.js.`),
    new Paragraph({ children: [new PageBreak()] }),
  ];
}

function renderBusinessPurpose(model) {
  return [
    h('Business Purpose', HeadingLevel.HEADING_1),
    p(model.businessPurpose),
  ];
}

function renderExecutiveSummary(model) {
  return [
    h('Executive Summary', HeadingLevel.HEADING_1),
    p(model.executiveSummary),
  ];
}

function renderSystemOverview(model) {
  const counts = {};
  for (const n of model.nodes) counts[n.type] = (counts[n.type] ?? 0) + 1;
  const rows = Object.entries(counts).map(([t, c]) => [t, String(c)]);
  return [
    h('System Overview', HeadingLevel.HEADING_1),
    p('The toolkit is composed of:'),
    table(['Component type', 'Count'], rows),
    p(''),
    p(`Plus ${model.edges.length} explicit relationships between them, ${model.flows.length} named data flows, and ${model.impactAnalysis.length} impact-analysis entries.`),
  ];
}

