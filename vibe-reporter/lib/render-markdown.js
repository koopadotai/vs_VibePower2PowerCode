/**
 * render-markdown.js — render the collected data bundle to a comprehensive
 * project documentation file (Markdown).
 *
 * Empty sections are silently skipped so the output stays compact on small
 * projects but grows with the project's actual artifacts.
 */

function bullet(items) {
  return items.map(i => `- ${i}`).join('\n');
}

function fmtDate(iso) {
  if (!iso) return '—';
  return new Date(iso).toISOString().replace('T', ' ').slice(0, 19) + ' UTC';
}

function sectionHeader(title) {
  return `\n## ${title}\n`;
}

function renderHistoryTable(versions) {
  if (versions.length === 0) return '_No version history yet._';
  const rows = versions.map(v => {
    const cf = v.changedFiles ?? { added: [], modified: [], deleted: [] };
    const tests = v.testResults
      ? `${v.testResults.passed ?? 0}P/${v.testResults.failed ?? 0}F`
      : '—';
    const note = (v.note || '').replace(/\|/g, '\\|') || '_(no note)_';
    return `| v${v.version} | ${fmtDate(v.extractedAt).slice(0, 10)} | +${cf.added?.length ?? 0} ~${cf.modified?.length ?? 0} -${cf.deleted?.length ?? 0} | ${v.fileCount ?? '—'} | ${tests} | ${note} |`;
  }).join('\n');
  return `| Version | Date | Diff | Files | Tests | Note |\n|---|---|---|---|---|---|\n${rows}`;
}

function renderVersionDetail(v) {
  const cf = v.changedFiles ?? { added: [], modified: [], deleted: [] };
  const parts = [];
  parts.push(`### v${v.version} — ${fmtDate(v.extractedAt).slice(0, 10)}\n`);
  if (v.note) parts.push(`> ${v.note}\n`);
  parts.push(`- **Files in this version:** ${v.fileCount ?? '—'}`);
  parts.push(`- **Tree hash:** \`${v.treeHash || '—'}\``);
  if (v.snapshotPath) parts.push(`- **Snapshot:** \`${v.snapshotPath}\``);
  if (v.gitTag) parts.push(`- **Git tag:** \`${v.gitTag}\``);
  if (v.testResults) {
    parts.push(`- **Tests (run at ${fmtDate(v.testResults.runAt)}):** ${v.testResults.passed ?? 0} passed, ${v.testResults.failed ?? 0} failed, ${v.testResults.skipped ?? 0} skipped (${((v.testResults.durationMs ?? 0) / 1000).toFixed(1)}s)`);
  }
  parts.push('');
  if (cf.added?.length) {
    parts.push('**Added files:**');
    parts.push(bullet(cf.added.map(f => `\`${f}\``)));
    parts.push('');
  }
  if (cf.modified?.length) {
    parts.push('**Modified files:**');
    parts.push(bullet(cf.modified.map(f => `\`${f}\``)));
    parts.push('');
  }
  if (cf.deleted?.length) {
    parts.push('**Deleted files:**');
    parts.push(bullet(cf.deleted.map(f => `\`${f}\``)));
    parts.push('');
  }
  return parts.join('\n');
}

/**
 * @param {object} data  Output of collect()
 * @returns {string}     Markdown document
 */
export function renderMarkdown(data) {
  const out = [];

  // ── Title block ──────────────────────────────────────────────────────────
  out.push(`# ${data.meta.projectName} — Project Documentation\n`);
  out.push(`**Current version:** v${data.meta.currentVersion}`);
  out.push(`**Generated:** ${fmtDate(data.meta.generatedAt)}`);
  if (data.powerConfig?.appDisplayName) out.push(`**App display name:** ${data.powerConfig.appDisplayName}`);
  if (data.powerConfig?.environmentId) out.push(`**Environment:** \`${data.powerConfig.environmentId}\` (${data.powerConfig.region ?? 'unknown region'})`);
  if (data.powerConfig?.appId) out.push(`**App ID:** \`${data.powerConfig.appId}\``);
  out.push('');
  out.push('> Auto-generated by `vibe-reporter`. Do not edit by hand — re-run `/migration-report` (or `node vibe-reporter/index.js`) to regenerate.');

  // ── Overview (from CONTEXT.md glossary if present) ───────────────────────
  if (data.context.glossary) {
    out.push(sectionHeader('Overview'));
    out.push(data.context.glossary);
  }

  // ── Architecture ─────────────────────────────────────────────────────────
  out.push(sectionHeader('Architecture'));
  out.push('This project was migrated from a Power Apps **Vibe** source (`make.powerapp.com`) to a Power Code project using **React + TypeScript** with the `@microsoft/power-apps` SDK.');
  out.push('');
  out.push('| Aspect | Value |');
  out.push('|---|---|');
  if (data.meta.powerCodeDir) out.push(`| Power Code project folder | \`${data.meta.powerCodeDir}/\` |`);
  if (data.powerConfig?.region) out.push(`| Region | ${data.powerConfig.region} |`);
  out.push(`| Models (Dataverse-generated) | ${data.models.length} |`);
  out.push(`| Connectors / data sources | ${data.connectors.length} |`);
  out.push(`| npm dependencies | ${data.dependencies.length} |`);

  // ── Migration history summary ────────────────────────────────────────────
  out.push(sectionHeader('Migration History'));
  out.push(renderHistoryTable(data.history));

  // ── Per-version detail ───────────────────────────────────────────────────
  if (data.history.length > 0) {
    out.push(sectionHeader('Version Details'));
    for (const v of data.history) out.push(renderVersionDetail(v));
  }

  // ── Field mappings ───────────────────────────────────────────────────────
  if (data.context.fieldMappings) {
    out.push(sectionHeader('Field Mappings'));
    out.push('Friendly Vibe field names ↔ raw Dataverse field names. The adapter layer (`src/generated/services/`) translates between them.');
    out.push('');
    out.push(data.context.fieldMappings);
  }

  // ── Data sources ─────────────────────────────────────────────────────────
  if (data.models.length > 0 || data.connectors.length > 0) {
    out.push(sectionHeader('Data Sources'));
    if (data.models.length > 0) {
      out.push('**Dataverse models:**');
      out.push(bullet(data.models.map(m => `\`${m}\``)));
      out.push('');
    }
    if (data.connectors.length > 0) {
      out.push('**Connectors:**');
      out.push(bullet(data.connectors.map(c => `\`${c}\``)));
      out.push('');
      out.push('> All connector calls go through `executeAsync({ connectorOperation })` from `@microsoft/power-apps/data` — direct `fetch()` is blocked by the Power Apps player CSP.');
    }
  }

  // ── File ownership ───────────────────────────────────────────────────────
  if (data.ownership) {
    out.push(sectionHeader('File Ownership'));
    out.push('From `vibe-migration.json`. Determines what incremental updates may auto-apply vs. require human review.');
    out.push('');
    if (data.ownership.vibeOwned.length > 0) {
      out.push(`**Vibe-owned** (${data.ownership.vibeOwned.length} files — safe to auto-update from new extractions):`);
      out.push(bullet(data.ownership.vibeOwned.map(f => `\`${f}\``)));
      out.push('');
    }
    if (data.ownership.migrationOwned.length > 0) {
      out.push(`**Migration-owned** (${data.ownership.migrationOwned.length} files — never auto-overwritten):`);
      out.push(bullet(data.ownership.migrationOwned.map(f => `\`${f}\``)));
      out.push('');
    }
    if (data.ownership.requiresReview.length > 0) {
      out.push(`**Requires review** (${data.ownership.requiresReview.length} files — diff shown, manual confirm):`);
      out.push(bullet(data.ownership.requiresReview.map(f => `\`${f}\``)));
      out.push('');
    }
  }

  // ── Architecture Decision Records ────────────────────────────────────────
  if (data.adrs.length > 0) {
    out.push(sectionHeader('Architecture Decisions (ADRs)'));
    for (const adr of data.adrs) {
      out.push(`### ${adr.title}`);
      out.push(`_Source: \`docs/adr/${adr.filename}\`_`);
      out.push('');
      // Strip the title line from the ADR body since we already have it
      const body = adr.body.replace(/^#\s+.+\n+/, '');
      out.push(body);
      out.push('');
    }
  }

  // ── Dependencies ─────────────────────────────────────────────────────────
  if (data.dependencies.length > 0) {
    out.push(sectionHeader('Dependencies'));
    out.push('**Runtime:**');
    out.push(bullet(data.dependencies.map(d => `\`${d}\``)));
    if (data.devDependencies.length > 0) {
      out.push('');
      out.push('**Development:**');
      out.push(bullet(data.devDependencies.map(d => `\`${d}\``)));
    }
  }

  // ── Footer ───────────────────────────────────────────────────────────────
  out.push('\n---\n');
  out.push(`_Generated by vibe-reporter at ${fmtDate(data.meta.generatedAt)}._`);

  return out.join('\n');
}
