/**
 * github-reporter.js — auto-create or comment on GitHub issues for test failures.
 *
 * Uses the `gh` CLI (must be installed and authenticated). For each failure:
 *   1. Search open issues labelled `test-failure` matching "<testName> @ v<version>".
 *   2. If found: post a comment with the new occurrence.
 *   3. If not: create a fresh issue with the failure body + labels.
 *
 * Returns the issue URL for each handled failure.
 */

import { execFileSync } from 'child_process';
import fs from 'fs';
import os from 'os';
import path from 'path';

const ISSUE_LABEL = 'test-failure';

function ghAvailable() {
  try {
    execFileSync('gh', ['--version'], { stdio: 'ignore' });
    return true;
  } catch { return false; }
}

function ghAuthenticated() {
  try {
    execFileSync('gh', ['auth', 'status'], { stdio: 'ignore' });
    return true;
  } catch { return false; }
}

function gh(args, opts = {}) {
  return execFileSync('gh', args, { encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'], ...opts });
}

function searchExistingIssue({ testName, version }) {
  // gh issue list --label test-failure --search "..." --state open --json number,title,url
  const query = `"${testName}" "v${version}" in:title`;
  try {
    const out = gh([
      'issue', 'list',
      '--label', ISSUE_LABEL,
      '--state', 'open',
      '--search', query,
      '--json', 'number,title,url',
      '--limit', '5',
    ]);
    const items = JSON.parse(out);
    // Match titles that mention both the test name and the version exactly.
    return items.find(i => i.title.includes(testName) && i.title.includes(`v${version}`)) ?? null;
  } catch {
    return null;
  }
}

function writeTemp(content, suffix = '.md') {
  const p = path.join(os.tmpdir(), `verify-${Date.now()}-${Math.random().toString(36).slice(2, 8)}${suffix}`);
  fs.writeFileSync(p, content, 'utf8');
  return p;
}

function formatIssueBody({ failure, appUrl, runAt }) {
  return `## Test failure

**Test**:    ${failure.testName}
**File**:    ${failure.file}${failure.line ? ':' + failure.line : ''}
**Version**: v${failure.version}
**Target**:  ${appUrl}
**Run at**:  ${runAt}

## Error

\`\`\`
${failure.error || '(no error message captured)'}
\`\`\`

## Reproduction

1. Sign in to the Power Apps player at the URL above.
2. Open the test file and follow the Playwright steps manually:
   \`${failure.file}\`
3. Compare with the trace / screenshot below.

## Artifacts

- Trace:      \`${failure.tracePath ?? '(not captured)'}\`
- Screenshot: \`${failure.screenshotPath ?? '(not captured)'}\`

---
🤖 Auto-generated by \`node vibe-verifier/index.js\`
`;
}

function formatCommentBody({ failure, runAt }) {
  return `## Recurrence at ${runAt}

\`\`\`
${failure.error || '(no error message captured)'}
\`\`\`

- Trace:      \`${failure.tracePath ?? '(not captured)'}\`
- Screenshot: \`${failure.screenshotPath ?? '(not captured)'}\`

🤖 Auto-posted by \`node vibe-verifier/index.js\`
`;
}

/**
 * @param {object} opts
 * @param {Array} opts.failures   Array of failure objects
 * @param {string} opts.appUrl
 * @param {function} [opts.log]
 * @returns {Array} per-failure result: { testName, action, url }
 */
export function reportFailures({ failures, appUrl, log = console.log }) {
  if (failures.length === 0) return [];
  if (!ghAvailable()) {
    log('  ! `gh` CLI not found — skipping GitHub issue creation.');
    log('    Install: https://cli.github.com/');
    return [];
  }
  if (!ghAuthenticated()) {
    log('  ! `gh` is not authenticated — skipping GitHub issue creation.');
    log('    Run: gh auth login');
    return [];
  }

  const runAt = new Date().toISOString();
  const results = [];

  for (const failure of failures) {
    const existing = searchExistingIssue(failure);
    let bodyPath;
    try {
      if (existing) {
        bodyPath = writeTemp(formatCommentBody({ failure, runAt }));
        gh(['issue', 'comment', String(existing.number), '--body-file', bodyPath]);
        log(`    ↳ commented on issue #${existing.number} (${existing.url})`);
        results.push({ testName: failure.testName, action: 'commented', url: existing.url, number: existing.number });
      } else {
        bodyPath = writeTemp(formatIssueBody({ failure, appUrl, runAt }));
        const title = `Test failed: ${failure.testName} @ v${failure.version}`;
        const labels = `${ISSUE_LABEL},v${failure.version},auto-generated`;
        const out = gh(['issue', 'create', '--title', title, '--body-file', bodyPath, '--label', labels]);
        const url = out.trim().split(/\s+/).pop();
        const number = url.split('/').pop();
        log(`    ↳ created issue #${number} (${url})`);
        results.push({ testName: failure.testName, action: 'created', url, number: Number(number) });
      }
    } catch (err) {
      log(`    ! gh call failed for "${failure.testName}": ${err.message}`);
      results.push({ testName: failure.testName, action: 'error', error: err.message });
    } finally {
      if (bodyPath) { try { fs.unlinkSync(bodyPath); } catch {} }
    }
  }

  return results;
}
