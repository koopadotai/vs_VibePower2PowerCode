/**
 * render-fleet-docx.js — render the fleet bundle to FLEET.docx.
 *
 * Mirrors render-fleet-md.js section structure so both outputs stay aligned.
 */

import {
  Document, Packer, Paragraph, TextRun, HeadingLevel, AlignmentType,
  Table, TableRow, TableCell, WidthType, BorderStyle, ShadingType, PageBreak,
} from 'docx';

function fmt(iso) {
  if (!iso) return '—';
  return new Date(iso).toISOString().replace('T', ' ').slice(0, 19) + ' UTC';
}

function fmtDaysAgo(days) {
  if (days == null) return '—';
  if (days < 0) return 'in future';
  if (days === 0) return 'today';
  if (days === 1) return 'yesterday';
  if (days < 30) return `${days}d ago`;
  if (days < 365) return `${Math.floor(days / 30)}mo ago`;
  return `${Math.floor(days / 365)}y ago`;
}

const HEALTH_LABEL = {
  ok: 'OK',
  'pending-update': 'Pending update',
  'tests-failed': 'Tests failed',
  stale: 'Stale',
  warning: 'Warning',
  missing: 'Missing',
  locked: 'Locked',
};

// ── Block helpers ───────────────────────────────────────────────────────────

function p(text, opts = {}) {
  return new Paragraph({
    spacing: { after: 120 },
    ...opts,
    children: [new TextRun({ text: text ?? '', ...opts.run })],
  });
}

function h(text, level) {
  return new Paragraph({
    heading: level,
    spacing: { before: 240, after: 120 },
    children: [new TextRun({ text })],
  });
}

function italic(text) { return new TextRun({ text, italics: true }); }

function bulletList(items) {
  return items.map(text =>
    new Paragraph({
      bullet: { level: 0 },
      spacing: { after: 60 },
      children: [new TextRun({ text })],
    })
  );
}

function quote(text) {
  return new Paragraph({
    indent: { left: 720 },
    spacing: { after: 120 },
    border: { left: { color: '888888', style: BorderStyle.SINGLE, size: 6, space: 12 } },
    children: [italic(text)],
  });
}

const HEADER_SHADING = { type: ShadingType.SOLID, color: 'EEEEEE', fill: 'EEEEEE' };

function cell(text, opts = {}) {
  return new TableCell({
    children: [
      new Paragraph({
        spacing: { after: 40 },
        children: [new TextRun({ text: String(text ?? ''), bold: opts.header ?? false })],
      }),
    ],
    shading: opts.header ? HEADER_SHADING : undefined,
  });
}

function table(headers, rows) {
  return new Table({
    width: { size: 100, type: WidthType.PERCENTAGE },
    rows: [
      new TableRow({ children: headers.map(h => cell(h, { header: true })) }),
      ...rows.map(r => new TableRow({ children: r.map(c => cell(c)) })),
    ],
  });
}

// ── Section renderers ───────────────────────────────────────────────────────

function renderCover(data) {
  return [
    new Paragraph({
      heading: HeadingLevel.TITLE,
      alignment: AlignmentType.CENTER,
      spacing: { before: 1440, after: 240 },
      children: [new TextRun({ text: data.meta.fleetName, bold: true, size: 56 })],
    }),
    new Paragraph({
      alignment: AlignmentType.CENTER,
      spacing: { after: 240 },
      children: [new TextRun({ text: 'Fleet Report', size: 32 })],
    }),
    new Paragraph({
      alignment: AlignmentType.CENTER,
      spacing: { after: 240 },
      children: [new TextRun({ text: `${data.meta.projectCount} project${data.meta.projectCount === 1 ? '' : 's'}`, size: 24 })],
    }),
    new Paragraph({
      alignment: AlignmentType.CENTER,
      spacing: { after: 480 },
      children: [new TextRun({ text: `Generated ${fmt(data.meta.generatedAt)}`, size: 20 })],
    }),
    quote(`Auto-generated by vibe-fleet report. Re-run after any extract/verify to refresh.`),
    new Paragraph({ children: [new PageBreak()] }),
  ];
}

function renderHealthSummary(data) {
  const out = [h('Health Summary', HeadingLevel.HEADING_1)];
  const counts = data.meta.healthCounts;
  const keys = Object.keys(counts).sort();
  if (keys.length === 0) {
    out.push(p('No projects to summarise.'));
    return out;
  }
  out.push(table(
    ['State', 'Count'],
    keys.map(k => [HEALTH_LABEL[k] ?? k, String(counts[k])]),
  ));
  return out;
}

function renderRoster(data) {
  const out = [h('Project Roster', HeadingLevel.HEADING_1)];
  if (data.projects.length === 0) {
    out.push(p('No projects registered yet.'));
    return out;
  }
  const rows = data.projects.map(proj => {
    const tests = proj.probe.lastTestRunAt
      ? `${proj.probe.lastTestPassed ?? 0}P/${proj.probe.lastTestFailed ?? 0}F`
      : '—';
    return [
      proj.alias,
      proj.probe.currentVersion ? `v${proj.probe.currentVersion}` : '—',
      proj.appDisplayName || '—',
      fmtDaysAgo(proj.probe.lastExtractedDaysAgo),
      proj.probe.hasPendingUpdate ? 'yes' : 'no',
      tests,
      HEALTH_LABEL[proj.probe.health] ?? proj.probe.health,
    ];
  });
  out.push(table(['Alias', 'Version', 'App', 'Last extract', 'Pending', 'Tests', 'Health'], rows));
  return out;
}

function renderProjectDetail(proj) {
  const out = [];
  out.push(h(proj.alias, HeadingLevel.HEADING_2));

  const metaRows = [];
  metaRows.push(['Path', proj.path]);
  if (proj.tags.length > 0)   metaRows.push(['Tags', proj.tags.join(', ')]);
  metaRows.push(['Registered', fmt(proj.registeredAt)]);
  if (proj.appDisplayName)    metaRows.push(['App display name', proj.appDisplayName]);
  if (proj.environmentId)     metaRows.push(['Environment ID', proj.environmentId]);
  if (proj.region)            metaRows.push(['Region', proj.region]);
  if (proj.appId)             metaRows.push(['App ID', proj.appId]);
  if (proj.packageVersion)    metaRows.push(['package.json version', proj.packageVersion]);
  if (proj.dependencyCount != null) metaRows.push(['npm dependencies', String(proj.dependencyCount)]);
  out.push(table(['Field', 'Value'], metaRows));

  const stateRows = [];
  stateRows.push(['Current version', proj.probe.currentVersion ? `v${proj.probe.currentVersion}` : '—']);
  stateRows.push(['Version history entries', String(proj.probe.versionCount)]);
  stateRows.push(['Last extracted', `${fmt(proj.probe.lastExtractedAt)} (${fmtDaysAgo(proj.probe.lastExtractedDaysAgo)})`]);
  stateRows.push(['Pending update', proj.probe.hasPendingUpdate ? `yes (v${proj.probe.pendingFromVersion} → v${proj.probe.pendingToVersion})` : 'no']);
  stateRows.push(['Lock present', proj.probe.hasLock ? `yes (pid ${proj.probe.lockHolderPid ?? '?'})` : 'no']);
  if (proj.probe.lastTestRunAt) {
    stateRows.push(['Last test run', `${fmt(proj.probe.lastTestRunAt)} — ${proj.probe.lastTestPassed}P / ${proj.probe.lastTestFailed}F / ${proj.probe.lastTestSkipped}S`]);
  } else {
    stateRows.push(['Last test run', 'never']);
  }
  stateRows.push(['Health', HEALTH_LABEL[proj.probe.health] ?? proj.probe.health]);
  out.push(p('State:', { run: { bold: true } }));
  out.push(table(['Field', 'Value'], stateRows));

  if (proj.probe.warnings.length > 0) {
    out.push(p('Warnings:', { run: { bold: true } }));
    out.push(...bulletList(proj.probe.warnings));
  }
  if (proj.contextSummary) {
    out.push(p('CONTEXT.md excerpt:', { run: { bold: true } }));
    out.push(quote(proj.contextSummary));
  }
  return out;
}

function renderTotals(data) {
  if (data.projects.length === 0) return [];
  const out = [h('Aggregated Totals', HeadingLevel.HEADING_1)];
  const totalVersions = data.projects.reduce((s, p) => s + (p.probe.versionCount || 0), 0);
  const withTests = data.projects.filter(p => p.probe.lastTestRunAt).length;
  const pending = data.projects.filter(p => p.probe.hasPendingUpdate).length;
  const failing = data.projects.filter(p => (p.probe.lastTestFailed ?? 0) > 0).length;
  const stale = data.projects.filter(p => p.probe.health === 'stale').length;
  out.push(table(['Metric', 'Value'], [
    ['Total version history entries across fleet', String(totalVersions)],
    ['Projects with at least one test run', `${withTests} / ${data.projects.length}`],
    ['Projects with unapplied pending updates', String(pending)],
    ['Projects with failing tests on last run', String(failing)],
    ['Projects with stale extractions (> 30 days)', String(stale)],
  ]));
  return out;
}

function renderFooter(data) {
  return [
    new Paragraph({
      spacing: { before: 480 },
      alignment: AlignmentType.CENTER,
      children: [italic(`Generated by vibe-fleet report at ${fmt(data.meta.generatedAt)}.`)],
    }),
  ];
}

// ── Public entry ────────────────────────────────────────────────────────────

export async function renderFleetDocx(data) {
  const children = [
    ...renderCover(data),
    ...renderHealthSummary(data),
    ...renderRoster(data),
  ];
  if (data.projects.length > 0) {
    children.push(h('Per-Project Detail', HeadingLevel.HEADING_1));
    for (const proj of data.projects) children.push(...renderProjectDetail(proj));
    children.push(...renderTotals(data));
  }
  children.push(...renderFooter(data));

  const doc = new Document({
    creator: 'vibe-fleet',
    title: `${data.meta.fleetName} — Fleet Report`,
    description: `Auto-generated fleet report (${data.meta.projectCount} projects)`,
    styles: {
      default: { document: { run: { font: 'Calibri', size: 22 } } },
    },
    sections: [{ properties: {}, children }],
  });

  return Packer.toBuffer(doc);
}
