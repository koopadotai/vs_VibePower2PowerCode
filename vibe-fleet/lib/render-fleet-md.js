/**
 * render-fleet-md.js — render the fleet bundle to FLEET.md.
 *
 * Sections (skipped silently if empty):
 *   1. Title + meta
 *   2. Health summary table
 *   3. Project roster (compact table)
 *   4. Per-project detail (one section per project)
 *   5. Aggregated totals
 *   6. Footer
 */

function fmt(iso) {
  if (!iso) return '—';
  return new Date(iso).toISOString().replace('T', ' ').slice(0, 19) + ' UTC';
}

function fmtDaysAgo(days) {
  if (days == null) return '—';
  if (days < 0) return 'in future';
  if (days === 0) return 'today';
  if (days === 1) return 'yesterday';
  if (days < 30) return `${days}d ago`;
  if (days < 365) return `${Math.floor(days / 30)}mo ago`;
  return `${Math.floor(days / 365)}y ago`;
}

const HEALTH_ICON = {
  ok: '✓',
  'pending-update': '⏳',
  'tests-failed': '✗',
  stale: '🕒',
  warning: '⚠',
  missing: '?',
  locked: '🔒',
};

function bullet(items) { return items.map(i => `- ${i}`).join('\n'); }

// ── Sections ───────────────────────────────────────────────────────────────

function renderTitle(data) {
  const out = [];
  out.push(`# ${data.meta.fleetName} — Fleet Report\n`);
  out.push(`**Generated:** ${fmt(data.meta.generatedAt)}`);
  out.push(`**Fleet created:** ${fmt(data.meta.fleetCreatedAt)}`);
  out.push(`**Config:** \`${data.meta.configPath}\` (via ${data.meta.configSource})`);
  out.push(`**Project count:** ${data.meta.projectCount}`);
  out.push('');
  out.push('> Auto-generated by `vibe-fleet report`. Re-run after any extract/verify to refresh.');
  return out.join('\n');
}

function renderHealthSummary(data) {
  const out = ['\n## Health Summary\n'];
  const counts = data.meta.healthCounts;
  const keys = Object.keys(counts).sort();
  if (keys.length === 0) {
    out.push('_No projects to summarise._');
    return out.join('\n');
  }
  out.push('| State | Icon | Count |');
  out.push('|---|---|---|');
  for (const k of keys) {
    out.push(`| ${k} | ${HEALTH_ICON[k] ?? '?'} | ${counts[k]} |`);
  }
  return out.join('\n');
}

function renderRoster(data) {
  const out = ['\n## Project Roster\n'];
  if (data.projects.length === 0) {
    out.push('_No projects registered yet._');
    return out.join('\n');
  }
  out.push('| Alias | Version | App | Env | Last extract | Pending | Tests | Health |');
  out.push('|---|---|---|---|---|---|---|---|');
  for (const p of data.projects) {
    const icon = HEALTH_ICON[p.probe.health] ?? '?';
    const tests = p.probe.lastTestRunAt
      ? `${p.probe.lastTestPassed ?? 0}P/${p.probe.lastTestFailed ?? 0}F`
      : '—';
    const lastExtract = fmtDaysAgo(p.probe.lastExtractedDaysAgo);
    const pending = p.probe.hasPendingUpdate ? 'yes' : 'no';
    const app = p.appDisplayName || '—';
    const env = p.environmentId ? `\`${p.environmentId.slice(0, 8)}…\`` : '—';
    out.push(`| \`${p.alias}\` | ${p.probe.currentVersion ? 'v' + p.probe.currentVersion : '—'} | ${app} | ${env} | ${lastExtract} | ${pending} | ${tests} | ${icon} ${p.probe.health} |`);
  }
  return out.join('\n');
}

function renderProjectDetail(p) {
  const out = [];
  const icon = HEALTH_ICON[p.probe.health] ?? '?';
  out.push(`### ${icon} \`${p.alias}\``);
  out.push('');
  out.push(`- **Path:** \`${p.path}\``);
  if (p.tags.length > 0) out.push(`- **Tags:** ${p.tags.map(t => `\`${t}\``).join(', ')}`);
  out.push(`- **Registered:** ${fmt(p.registeredAt)}`);
  if (p.appDisplayName)   out.push(`- **App display name:** ${p.appDisplayName}`);
  if (p.environmentId)    out.push(`- **Environment ID:** \`${p.environmentId}\` (${p.region ?? 'unknown region'})`);
  if (p.appId)            out.push(`- **App ID:** \`${p.appId}\``);
  if (p.packageVersion)   out.push(`- **package.json version:** \`${p.packageVersion}\``);
  if (p.dependencyCount != null) out.push(`- **npm dependencies:** ${p.dependencyCount}`);
  out.push('');
  out.push('**State:**');
  out.push('');
  out.push(`- **Current version:** ${p.probe.currentVersion ? 'v' + p.probe.currentVersion : '—'}`);
  out.push(`- **Version history entries:** ${p.probe.versionCount}`);
  out.push(`- **Last extracted:** ${fmt(p.probe.lastExtractedAt)} (${fmtDaysAgo(p.probe.lastExtractedDaysAgo)})`);
  out.push(`- **Pending update:** ${p.probe.hasPendingUpdate ? `yes (v${p.probe.pendingFromVersion} → v${p.probe.pendingToVersion})` : 'no'}`);
  out.push(`- **Lock present:** ${p.probe.hasLock ? `yes (pid ${p.probe.lockHolderPid ?? '?'})` : 'no'}`);
  if (p.probe.lastTestRunAt) {
    out.push(`- **Last test run:** ${fmt(p.probe.lastTestRunAt)} — ${p.probe.lastTestPassed}P / ${p.probe.lastTestFailed}F / ${p.probe.lastTestSkipped}S`);
  } else {
    out.push('- **Last test run:** never');
  }
  out.push(`- **Health:** ${icon} **${p.probe.health}**`);
  out.push('');
  if (p.probe.warnings.length > 0) {
    out.push('**Warnings:**');
    out.push(bullet(p.probe.warnings));
    out.push('');
  }
  if (p.contextSummary) {
    out.push('**CONTEXT.md excerpt:**');
    out.push('');
    out.push(`> ${p.contextSummary}`);
    out.push('');
  }
  return out.join('\n');
}

function renderTotals(data) {
  if (data.projects.length === 0) return '';
  const out = ['\n## Aggregated Totals\n'];
  const totalVersions = data.projects.reduce((s, p) => s + (p.probe.versionCount || 0), 0);
  const withTests = data.projects.filter(p => p.probe.lastTestRunAt).length;
  const pending = data.projects.filter(p => p.probe.hasPendingUpdate).length;
  const failing = data.projects.filter(p => (p.probe.lastTestFailed ?? 0) > 0).length;
  const stale = data.projects.filter(p => p.probe.health === 'stale').length;
  out.push('| Metric | Value |');
  out.push('|---|---|');
  out.push(`| Total version history entries across fleet | ${totalVersions} |`);
  out.push(`| Projects with at least one test run | ${withTests} / ${data.projects.length} |`);
  out.push(`| Projects with unapplied pending updates | ${pending} |`);
  out.push(`| Projects with failing tests on last run | ${failing} |`);
  out.push(`| Projects with stale extractions (> 30 days) | ${stale} |`);
  return out.join('\n');
}

function renderFooter(data) {
  return `\n---\n\n_Generated by \`vibe-fleet report\` at ${fmt(data.meta.generatedAt)}._`;
}

// ── Public ─────────────────────────────────────────────────────────────────

export function renderFleetMarkdown(data) {
  const parts = [
    renderTitle(data),
    renderHealthSummary(data),
    renderRoster(data),
  ];
  if (data.projects.length > 0) {
    parts.push('\n## Per-Project Detail\n');
    for (const p of data.projects) parts.push(renderProjectDetail(p));
    parts.push(renderTotals(data));
  }
  parts.push(renderFooter(data));
  return parts.join('\n');
}
